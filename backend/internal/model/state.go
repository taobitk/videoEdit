package model

// SystemCapabilities describes detected FFmpeg binaries and NVIDIA GPU support.
type SystemCapabilities struct {
	FFmpegAvailable  bool   `json:"ffmpeg_available"`
	FFprobeAvailable bool   `json:"ffprobe_available"`
	HasNvidiaGPU     bool   `json:"has_nvidia_gpu"`
	GPUName          string `json:"gpu_name"`
	NvencH264        bool   `json:"nvenc_h264"`
	NvencHEVC        bool   `json:"nvenc_hevc"`
}

// ProbeResponse represents media metadata returned by POST /api/probe.
type ProbeResponse struct {
	Success    bool    `json:"success"`
	Path       string  `json:"path"`
	Width      int     `json:"width"`
	Height     int     `json:"height"`
	RawWidth   int     `json:"raw_width"`
	RawHeight  int     `json:"raw_height"`
	Rotation   int     `json:"rotation"`
	Duration   float64 `json:"duration"`
	FPS        float64 `json:"fps"`
	VideoCodec string  `json:"video_codec"`
	HasAudio   bool    `json:"has_audio"`
	AudioCodec string  `json:"audio_codec"`
	StartTime   float64 `json:"start_time"`
	SizeMB      float64 `json:"size_mb"`
	BitrateKbps int     `json:"bitrate_kbps"`
}

// OutputFile describes a downloadable file generated by the engine.
type OutputFile struct {
	Filename string `json:"filename"`
	URL      string `json:"url"`
}

// EngineStatus is the live state snapshot served by /api/status and /api/events.
type EngineStatus struct {
	Status         string       `json:"status"`
	Mode           string       `json:"mode"`
	Progress       float64      `json:"progress"`
	FPS            float64      `json:"fps"`
	Speed          string       `json:"speed"`
	TimeProcessed  string       `json:"time_processed"`
	ETA            string       `json:"eta"`
	CurrentStep    string       `json:"current_step"`
	ActiveEncoder  string       `json:"active_encoder"`
	EncoderDetail  string       `json:"encoder_detail"`
	ErrorMessage   string       `json:"error_message"`
	OutputFilename string       `json:"output_filename"`
	OutputURL      string       `json:"output_url"`
	OutputFiles    []OutputFile `json:"output_files"`
	Warnings       []string     `json:"warnings"`
	Logs           []string     `json:"logs"`
}

// NewInitialStatus returns a clean idle status with non-nil slices for JSON safety.
func NewInitialStatus() EngineStatus {
	return EngineStatus{
		Status:        "idle",
		Mode:          "process",
		Speed:         "0x",
		TimeProcessed: "00:00:00",
		OutputFiles:   []OutputFile{},
		Warnings:      []string{},
		Logs:          []string{},
	}
}

// Clone returns a deep copy of EngineStatus safe for concurrent serialization.
func (s EngineStatus) Clone() EngineStatus {
	out := s
	out.OutputFiles = make([]OutputFile, len(s.OutputFiles))
	copy(out.OutputFiles, s.OutputFiles)
	out.Warnings = make([]string, len(s.Warnings))
	copy(out.Warnings, s.Warnings)
	out.Logs = make([]string, len(s.Logs))
	copy(out.Logs, s.Logs)
	return out
}
